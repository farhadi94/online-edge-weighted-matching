#!/usr/bin/env python3
"""Generate the exact, compact small-threshold tournament certificate.

Only Python's standard library is used.  Lean checks every emitted rational
reciprocal bound, the prefix recurrence, and the final natural-number margin.
"""

from fractions import Fraction
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def ceil_div(numerator: int, denominator: int) -> int:
    assert numerator >= 0 and denominator > 0
    return (numerator + denominator - 1) // denominator


def lookup_tree(rows: list[str], indent: str = "") -> str:
    if len(rows) == 1:
        return f".leaf {rows[0]}"
    middle = len(rows) // 2
    left = lookup_tree(rows[:middle], indent + "  ")
    right = lookup_tree(rows[middle:], indent + "  ")
    return f".branch {middle} (\n{indent}  {left}) (\n{indent}  {right})"


def main() -> None:
    source = json.loads((ROOT / "verification/fresh-direct500.json").read_text())
    scale = source["scale"]
    fresh_rows = source["rows"]
    assert len(fresh_rows) == 500
    denominator_power = 1000000**498
    numerator_power = 999999**498
    rows = []
    prefix = 0
    tightest = (Fraction(0), 0)
    for n, fresh in enumerate(fresh_rows):
        lower_b, _, _, a, e, _, theta = fresh
        assert 0 < lower_b and 2 * lower_b >= scale and 50 * a >= scale
        assert 0 <= theta <= scale and 0 < a <= e
        upper = ceil_div((scale - theta) * scale, e) + ceil_div(theta * scale, a)
        exact = Fraction(scale - theta, e) + Fraction(theta, a)
        assert exact <= Fraction(upper, scale)
        if n >= 2:
            lhs = 9 * prefix * (500 - n) * denominator_power
            rhs = 4490 * n * lower_b * numerator_power
            assert lhs <= rhs, f"small-threshold margin fails at r={n}"
            tightest = max(tightest, (Fraction(lhs, rhs), n))
        rows.append((lower_b, upper, prefix))
        prefix += upper

    scalar_leaves = [f"⟨{lb}, {upper}, {prefix}⟩" for lb, upper, prefix in rows]
    fresh_leaves = ["⟨" + ", ".join(str(v) for v in row) + "⟩" for row in fresh_rows]
    module = f'''import WeightedMatching.TournamentCertificateSmall

/-! Generated by scripts/generate_small_threshold500.py.

Each row gives one rounded reciprocal bound and its exact prefix sum.
All 498 small-threshold margins are checked by Lean's kernel.
-/

namespace WeightedMatching

noncomputable section

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async true

def smallThresholdRows500 : CertificateLookup SmallThresholdIntegerRow :=
  {lookup_tree(scalar_leaves, "  ")}

def smallThresholdFreshNatRows500 : CertificateLookup FreshNatRow :=
  {lookup_tree(fresh_leaves, "  ")}

def smallThresholdFreshRows500 : CertificateLookup FreshNumericalRow :=
  smallThresholdFreshNatRows500.map (FreshNatRow.toNumerical {scale})

theorem smallThresholdFreshRows500_valid : smallThresholdFreshRows500.valid = true := by decide

theorem smallThresholdFreshRows500_lookup (n : ℕ) :
    smallThresholdFreshRows500.lookup freshDefaultRow n =
      (smallThresholdFreshNatRows500.lookup (freshNatScaleDefault {scale}) n).toNumerical {scale} := by
  unfold smallThresholdFreshRows500
  rw [← freshNatScaleDefault_toNumerical {scale} (by decide)]
  exact CertificateLookup.lookup_map _ _ _ n

def smallThresholdIndexTree500 : CertificateLookup ℕ :=
  {lookup_tree([str(n) for n in range(500)], "  ")}

theorem smallThresholdIndexTree500_entries :
    smallThresholdIndexTree500.entries = List.range 500 := by decide

def smallThresholdDenominatorPower500 : ℕ := {denominator_power}
def smallThresholdNumeratorPower500 : ℕ := {numerator_power}

theorem smallThresholdDenominatorPower500_correct :
    smallThresholdDenominatorPower500 = 1000000 ^ 498 := by
  norm_num [smallThresholdDenominatorPower500]

theorem smallThresholdNumeratorPower500_correct :
    smallThresholdNumeratorPower500 = 999999 ^ 498 := by
  norm_num [smallThresholdNumeratorPower500]

theorem smallThresholdCheck500 : smallThresholdIndexTree500.checkAll
    (fun n => decide (smallThresholdNatTreeCondition {scale}
      smallThresholdDenominatorPower500 smallThresholdNumeratorPower500
      smallThresholdFreshNatRows500 smallThresholdRows500 n)) = true := by
  decide +kernel

def smallThresholdNumerical500 :
    SmallThresholdNumericalCertificate smallThresholdFreshRows500.entries where
  scale := {scale}
  scale_pos := by decide
  rows := smallThresholdRows500.lookup smallThresholdDefaultRow
  checked := by
    intro n
    have hn : n.val ∈ smallThresholdIndexTree500.entries := by
      rw [smallThresholdIndexTree500_entries]
      exact List.mem_range.mpr n.isLt
    have hc := smallThresholdIndexTree500.checkAll_sound
      (fun i => decide (smallThresholdNatTreeCondition {scale}
        smallThresholdDenominatorPower500 smallThresholdNumeratorPower500
        smallThresholdFreshNatRows500 smallThresholdRows500 i)) smallThresholdCheck500 n.val hn
    have hnat := of_decide_eq_true hc
    unfold smallThresholdNatTreeCondition at hnat
    have hfast := smallThresholdNatRowCondition_sound {scale} _ _ (by decide) _ _ _ n.val hnat
    have h := smallThresholdFastRowCondition_sound {scale} _ _
      smallThresholdDenominatorPower500_correct smallThresholdNumeratorPower500_correct
      _ _ _ n.val hfast
    rw [← smallThresholdFreshRows500_lookup n.val] at h
    rw [smallThresholdFreshRows500.lookup_eq_getD smallThresholdFreshRows500_valid] at h
    exact h

end

end WeightedMatching
'''
    module = module.replace("\ndef ", "\nnoncomputable def ")
    split_at = module.index("theorem smallThresholdCheck500")
    data_module = module[:split_at] + "end\n\nend WeightedMatching\n"
    proof_module = """import WeightedMatching.TournamentCertificateSmall500Data

namespace WeightedMatching

noncomputable section

set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async true

""" + module[split_at:]
    (ROOT / "WeightedMatching/TournamentCertificateSmall500Data.lean").write_text(data_module, encoding="utf-8")
    (ROOT / "WeightedMatching/TournamentCertificateSmall500.lean").write_text(proof_module, encoding="utf-8")
    evidence = {
        "scale": scale,
        "fields": ["lowerB", "upper", "prefix"],
        "rows": rows,
        "threshold": [1, 1000000],
        "tightest_r": tightest[1],
        "tightest_ratio_decimal": float(tightest[0]),
    }
    (ROOT / "verification/small-threshold500.json").write_text(
        json.dumps(evidence, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Generated 500 rows; tightest r={tightest[1]}, ratio={float(tightest[0]):.12f}")


if __name__ == "__main__":
    main()
